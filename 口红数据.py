    for i, 一项 in enumerate(_原始列表):
        口红 = dict(一项)
        口红["id"] = f"{口红['品牌']}-{口红['名称']}-{口红['色号']}-{i}"
        口红["全名"] = f"{口红['品牌']} {口红['名称']} {口红['色号']}"
        口红["简称"] = f"{口红['品牌']} {口红['色号']}"
        口红.setdefault("图片", 色系图片.get(口红["色系"], "tomato.png"))
        if 口红["色系"] == "樱桃":
            口红["色系"] = "正红"
            口红["图片"] = 色系图片["正红"]
        键 = (一项["品牌"], 一项["名称"], 一项["色号"])
        口红["介绍"] = 详细介绍.get(键, 口红["说明"])
        淘 = (推广链接.get(键) or "").strip()
        京 = (京东推广链接.get(键) or "").strip()
        拼 = (拼多多推广链接.get(键) or "").strip()
        唯 = (唯品会推广链接.get(键) or "").strip()
        口红["淘宝推广"] = 淘
        口红["京东推广"] = 京
        口红["拼多多推广"] = 拼
        口红["唯品会推广"] = 唯
        if 淘:
            口红["有佣金"] = True
            口红["佣金渠道"] = "淘宝"
            口红["购买链接"] = 淘
        elif 京:
            口红["有佣金"] = True
            口红["佣金渠道"] = "京东"
            口红["购买链接"] = 京
        elif 拼:
            口红["有佣金"] = True
            口红["佣金渠道"] = "拼多多"
            口红["购买链接"] = 拼
        elif 唯:
            口红["有佣金"] = True
            口红["佣金渠道"] = "唯品会"
            口红["购买链接"] = 唯
        else:
            口红["有佣金"] = False
            口红["佣金渠道"] = ""
